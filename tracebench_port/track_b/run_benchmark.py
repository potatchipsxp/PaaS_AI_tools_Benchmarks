#!/usr/bin/env python3
"""
run_benchmark.py  (Track B -- trace-native, deterministic query_trace)

Benchmark runner. Iterates over the 27 TraceBench cases in
BENCHMARK_CASES_TRACE, calls diagnose() on each, and writes a results JSON
file. Forked from Track A's run_benchmark.py -- structurally identical,
minus the SQL sub-agent (Track B has none, see diagnostic_agent.py's
module docstring).

Usage:
    python run_benchmark.py
    python run_benchmark.py --tier 3       # only Tier 3 cases
    python run_benchmark.py --tier 0       # only the 7 normal controls
    python run_benchmark.py --limit 5      # only first 5 cases
    python run_benchmark.py --output my_run.json   # override filename

For a quick wiring smoke test instead of a full benchmark:
    python diagnostic_agent.py
"""

import argparse
import os
import sys

sys.path.insert(0, "..")
from benchmark_cases_trace import BENCHMARK_CASES_TRACE  # noqa: E402

from diagnostic_agent import (
    build_diagnostic_agent,
    diagnose,
    save_results,
    OUTPUT_FILE,
    DIAGNOSTIC_MODEL,
    DIAGNOSTIC_BACKEND,
    DOC_MODEL,
    DOC_BACKEND,
    VERBOSE,
)


def main():
    RESULTS_DIR = "Results"
    os.makedirs(RESULTS_DIR, exist_ok=True)
    default_output = os.path.join(RESULTS_DIR, OUTPUT_FILE)

    ap = argparse.ArgumentParser(description=__doc__.split("\n")[2])
    ap.add_argument("--tier", type=int, choices=[0, 1, 2, 3],
                    help="run only cases at this tier (0 = normal controls; default: all)")
    ap.add_argument("--limit", type=int,
                    help="run only the first N cases (default: all)")
    ap.add_argument("--output", default=default_output,
                    help=f"output filename (default: Results/<auto-generated name>)")
    args = ap.parse_args()

    # Filter cases based on flags
    cases = BENCHMARK_CASES_TRACE
    if args.tier is not None:
        cases = [c for c in cases if c.get("tier") == args.tier]
        print(f"Filtering to Tier {args.tier} cases only.")
    if args.limit is not None:
        cases = cases[:args.limit]
        print(f"Limiting to first {args.limit} case(s).")

    if not cases:
        sys.exit("No cases matched the filter — nothing to run.")

    # Print run header
    print("=" * 70)
    print("BENCHMARK RUN (Track B -- trace-native)")
    print("=" * 70)
    print(f"Diagnostic model : {DIAGNOSTIC_MODEL} ({DIAGNOSTIC_BACKEND})")
    print(f"Doc model        : {DOC_MODEL} ({DOC_BACKEND})")
    print(f"Cases            : {len(cases)} of {len(BENCHMARK_CASES_TRACE)}")
    print(f"Output file      : {args.output}")
    print("=" * 70)

    # Build the orchestrator agent once and reuse it across all cases
    agent, tools, trace = build_diagnostic_agent()

    # Run each case
    all_results = []
    for case in cases:
        result = diagnose(
            incident_id=case["case_id"],
            question=case["question"],
            agent=agent,
            trace=trace,
            verbose=VERBOSE,
        )
        all_results.append(result)

    # Save
    save_results(all_results, output_file=args.output)

    print()
    print("=" * 70)
    print(f"Benchmark complete. {len(all_results)} case(s) processed.")
    print(f"Results saved to: {args.output}")
    print("Next: python ../evaluate_trace.py")
    print("=" * 70)


if __name__ == "__main__":
    main()
